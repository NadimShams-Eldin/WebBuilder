const DICTS: Record<Locale, Record<string, string>> = { ar, en }

export function translate(locale: Locale, key: string): string {
  return DICTS[locale][key] ?? DICTS.ar[key] ?? key
}

export function missingI18nKeys(): string[] {
  return Object.keys(ar).filter((key) => !(key in en))
}
